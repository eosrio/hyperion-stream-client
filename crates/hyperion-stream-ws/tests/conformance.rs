use hyperion_stream_core::*;
use hyperion_stream_ws::codec;
use serde_json::{json, Value};

fn event_json(event: Event<Value>) -> Value {
    match event {
        Event::Connected(h) => {
            json!({"type":"connected","connection_id":h.connection_id.to_string()})
        }
        Event::Accepted { scope, start_from } => {
            json!({"type":"accepted","stream_id":scope.stream_id.to_string(),"generation":scope.generation.to_string(),"subscription_id":scope.subscription_id.to_string(),"start_from":start_from})
        }
        Event::Data(b) => {
            json!({"type":"data","stream_id":b.scope.stream_id.to_string(),"generation":b.scope.generation.to_string(),"sequence":b.sequence.to_string(),"blocks":b.records.iter().map(|r|r.block_num).collect::<Vec<_>>(),"cursors":b.records.iter().map(|r|r.cursor.map(|n|n.to_string())).collect::<Vec<_>>(),"payloads":b.records.into_iter().map(|r|r.payload).collect::<Vec<_>>()})
        }
        Event::HistoryEnd { stream_id } => {
            json!({"type":"history_end","stream_id":stream_id.to_string()})
        }
        Event::End { stream_id } => json!({"type":"end","stream_id":stream_id.to_string()}),
        Event::Cancelled { stream_id } => {
            json!({"type":"cancelled","stream_id":stream_id.to_string()})
        }
        Event::Error(e) => {
            json!({"type":"error","stream_id":e.stream_id.map(|n|n.to_string()),"code":e.code,"retryable":e.retryable})
        }
        Event::Lib(lib) => json!({"type":"lib","block_num":lib.block_num}),
        Event::Fork(fork) => {
            json!({"type":"fork","starting_block":fork.starting_block,"ending_block":fork.ending_block})
        }
        Event::Disconnected => json!({"type":"disconnected"}),
    }
}

// Expectations are literal protocol assertions, not snapshots generated by the
// implementation. Objects may select public fields; arrays always match exactly.
fn assert_fields(actual: &Value, expected: &Value, context: &str) {
    match expected {
        Value::Object(fields) => {
            for (key, value) in fields {
                assert!(
                    actual.get(key).is_some(),
                    "{context}: missing {key}: {actual}"
                );
                assert_fields(&actual[key], value, context);
            }
        }
        Value::Array(values) => {
            assert_eq!(
                actual.as_array().map(Vec::len),
                Some(values.len()),
                "{context}: {actual}"
            );
            for (a, e) in actual.as_array().unwrap().iter().zip(values) {
                assert_fields(a, e, context);
            }
        }
        _ => assert_eq!(actual, expected, "{context}"),
    }
}

#[test]
fn shared_state_machine_scenarios() {
    let corpus: Value =
        serde_json::from_str(include_str!("../../../conformance/v1/scenarios.json")).unwrap();
    for case in corpus["cases"].as_array().unwrap() {
        let mut config = Config::default();
        for (key, value) in case["config"].as_object().into_iter().flatten() {
            let n = value.as_u64().unwrap();
            match key.as_str() {
                "stream_records" => config.stream_window.records = n as usize,
                "stream_bytes" => config.stream_window.bytes = n as usize,
                "connection_records" => config.connection_window.records = n as usize,
                "connection_bytes" => config.connection_window.bytes = n as usize,
                "request_timeout_ms" => config.request_timeout_ms = n,
                "lib_timeout_ms" => config.lib_timeout_ms = n,
                _ => panic!("Unknown fixture config {key}"),
            }
        }
        let mut client = Client::<Value, Value>::new(config).unwrap();
        for (index, step) in case["steps"].as_array().unwrap().iter().enumerate() {
            let id = || step["stream_id"].as_str().unwrap().parse::<u64>().unwrap();
            let result = match step["op"].as_str().unwrap() {
                "server" => codec::decode(&step["packet"].to_string())
                    .and_then(|input| client.receive(input)),
                "subscribe" => client.subscribe(
                    id(),
                    step["request"].clone(),
                    if step["delivery"] == "irreversible" {
                        Delivery::Irreversible
                    } else {
                        Delivery::Head
                    },
                    step["replay"].as_bool().unwrap_or(true),
                ),
                "poll" => Ok(client.poll()),
                "cancel" => Ok(client.cancel(id())),
                "disconnect" => client.disconnect(),
                "advance" => client.advance(step["now_ms"].as_u64().unwrap()),
                op => panic!("Unknown fixture operation {op}"),
            };
            let actual = match result {
                Ok(t) => {
                    json!({"commands":t.commands.iter().map(codec::command_json).collect::<Result<Vec<_>,_>>().unwrap(),"events":t.events.into_iter().map(event_json).collect::<Vec<_>>()})
                }
                Err(e) => json!({"fatal":e.code}),
            };
            assert_fields(
                &actual,
                &step["expect"],
                &format!("{} step {index}", case["name"]),
            );
        }
    }
}
